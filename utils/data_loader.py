import json
import logging

import pandas as pd

from config.settings import CLEAN_DATA_PATH, METRICS_JSON_PATH

logger = logging.getLogger("data_loader")


def load_processed_data() -> pd.DataFrame:
    """Load the cleaned and engineered dataset."""
    if not CLEAN_DATA_PATH.exists():
        logger.error(f"Dataset not found at {CLEAN_DATA_PATH}")
        return pd.DataFrame()

    try:
        df = pd.read_csv(CLEAN_DATA_PATH)
        logger.info(f"Loaded data with shape: {df.shape}")
        logger.info(f"Columns: {list(df.columns)}")

        # Ensure consistent date parsing
        if "year" in df.columns and "month" in df.columns:
            df["date"] = pd.to_datetime(df[["year", "month"]].assign(day=1))
            df = df.sort_values(by="date")
            logger.info(f"Date range: {df['date'].min()} to {df['date'].max()}")

        # Verify required columns exist
        required_cols = ["icp_price", "wti_price"]
        missing = [col for col in required_cols if col not in df.columns]
        if missing:
            logger.error(f"Missing required columns: {missing}")
            return pd.DataFrame()

        return df
    except Exception as e:
        logger.error(f"Failed to load data: {str(e)}")
        return pd.DataFrame()


def load_pipeline_metrics() -> dict:
    """Load metrics generated by the training pipeline."""
    if not METRICS_JSON_PATH.exists():
        logger.warning(f"Metrics file not found at {METRICS_JSON_PATH}")
        return {"best_model": "Unknown", "rmse": 0.0, "mae": 0.0}

    try:
        with open(METRICS_JSON_PATH, "r") as f:
            return json.load(f)
    except Exception as e:
        logger.error(f"Failed to load metrics: {str(e)}")
        return {"best_model": "Error", "rmse": 0.0, "mae": 0.0}


def get_latest_context(df: pd.DataFrame) -> dict:
    """Extract the most recent features for inference."""
    if df.empty:
        logger.warning("Empty dataframe provided to get_latest_context")
        return {}

    latest = df.iloc[-1]
    logger.info(f"Latest row columns: {list(latest.index)}")

    # This mapping must align with FEATURE_COLUMNS in settings.py
    context = {
        "lag_1": float(latest.get("icp_price", latest.get("lag_1", 0.0))),
        "lag_3": float(latest.get("lag_3", 0.0)),
        "lag_6": float(latest.get("lag_6", 0.0)),
        "wti_price": float(latest.get("wti_price", 0.0)),
        "rolling_mean_3": float(latest.get("rolling_mean_3", 0.0)),
        "wti_lag_1": float(latest.get("wti_lag_1", 0.0)),
        "wti_rolling_mean_3": float(latest.get("wti_rolling_mean_3", 0.0)),
    }

    logger.info(f"Extracted context: {context}")
    return context
